// Aggregates test-results/contrast/**/*.json (written by the worst-case art captures) into docs/design/contrast-report.md.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const inputDir = join(root, "test-results", "contrast");
const outputFile = join(root, "docs", "design", "contrast-report.md");

const escapeCell = (text) => text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/`/g, "\\`").replace(/\s+/g, " ");
const px = (value) => `${Math.round(value * 100) / 100} px`;

// results: [{ capture, runs: [{ text, fontSizePx, required, ratio, lowest, x, y }] }]
export function renderReport(results) {
  const captures = [...results].sort((a, b) => (a.capture < b.capture ? -1 : a.capture > b.capture ? 1 : 0));
  const failing = (run) => run.ratio < run.required;
  const lines = [
    "# Contrast report",
    "",
    "Generated by `pnpm test:visual` from the worst-case artwork captures (P13-30); do not edit by hand. "
      + "Each capture is taken twice: once as shown, and once with text hidden and text shadows removed, so the pixels behind every visible text run can be read. "
      + "Scrims and gradients stay in the picture. "
      + "Because shadows are removed, a failure may be text that is legible only through its own text-shadow, so read these numbers as the worst case and not as proof that a scrim is missing. "
      + "The measured ratio is the 5th percentile of the per-pixel contrast between the text (with its opacity) and the pixels behind it, "
      + "so 95% of the background meets it; the lowest ratio is shown for context. "
      + "Thresholds follow DESIGN.md section 11 rule 1: 3:1 for 24 px and up or 18.66 px at weight 700 and up, otherwise 4.5:1. "
      + "Text is not tested for occlusion by other elements, and non-text contrast is out of scope.",
    "",
    "## Summary",
    "",
    "| Capture | Text runs | Failures |",
    "| --- | --- | --- |",
    ...captures.map((c) => `| ${c.capture} | ${c.runs.length} | ${c.runs.filter(failing).length} |`),
    "",
    "## Failures",
    "",
  ];
  const rows = captures.flatMap((c) => c.runs.filter(failing).map((run) => `| ${c.capture} | ${escapeCell(run.text)} | ${px(run.fontSizePx)} | ${run.required}:1 | ${run.ratio.toFixed(2)}:1 | ${run.lowest.toFixed(2)}:1 |`));
  if (rows.length === 0) {
    lines.push("No text run is below its threshold.");
  } else {
    lines.push("| Capture | Text | Size | Needed | Measured | Lowest |", "| --- | --- | --- | --- | --- | --- |", ...rows);
  }
  return `${lines.join("\n")}\n`;
}

function readResults(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...readResults(path));
    else if (entry.name.endsWith(".json")) out.push(JSON.parse(readFileSync(path, "utf8")));
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const results = existsSync(inputDir) ? readResults(inputDir) : [];
  if (results.length === 0) {
    console.log("no contrast results; report unchanged");
  } else {
    mkdirSync(dirname(outputFile), { recursive: true });
    writeFileSync(outputFile, renderReport(results));
    console.log(`wrote ${outputFile} from ${results.length} captures`);
  }
}
