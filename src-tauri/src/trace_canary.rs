//! A heuristic check that trace output does not name a play session or an id.
//!
//! It reads every Rust file under `src/` at runtime, so a new module is scanned
//! without being listed. A file is skipped only when its module is declared
//! under `#[cfg(test)]` (or sits below such a module); inside a file, only the
//! bodies of `#[cfg(test)] mod … { … }` blocks are skipped. Comments and the
//! contents of string and char literals are blanked before braces and calls
//! are matched.
//!
//! A trace call is `eprintln!`, `eprint!`, `println!`, `print!`, `dbg!`,
//! `native_trace`, or `realtime_trace`, anywhere in a line, read from its name
//! to its closing delimiter. It fails the check when it mentions "session",
//! formats an identifier that names an id (`id`, `sid`, `*_id`, `*Id`) as a
//! placeholder or an argument, forwards a `macro_rules!` argument, or forwards
//! a parameter of its enclosing fn (other than the two trace helpers).
//!
//! It cannot see through values built elsewhere (a `String` assembled earlier
//! and passed in under an unrelated name), other logging crates, or code
//! generated by build scripts. Review still owns those.

mod code_view;
#[cfg(test)]
mod tests;
mod traces;

use crate::command_allowlist::collect_rust_files;
use code_view::code_view;
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use traces::{cfg_test_modules, session_traces};

struct Scan {
    scanned: BTreeSet<PathBuf>,
    hits: Vec<String>,
}

/// Scans `sources` (path, text) and reports every trace in production code
/// that could name a session or an id.
fn scan(sources: &[(PathBuf, String)]) -> Scan {
    let test_only = test_only_modules(sources);
    let mut scanned = BTreeSet::new();
    let mut hits = Vec::new();
    for (path, source) in sources {
        if test_only
            .iter()
            .any(|module| path == &module.with_extension("rs") || path.starts_with(module))
        {
            continue;
        }
        scanned.insert(path.clone());
        for hit in session_traces(source) {
            hits.push(format!("{}: {hit}", path.display()));
        }
    }
    Scan { scanned, hits }
}

/// Module paths (without extension) declared as `#[cfg(test)] mod name;`.
/// `a/b` covers both `a/b.rs` and everything under `a/b/`.
fn test_only_modules(sources: &[(PathBuf, String)]) -> Vec<PathBuf> {
    let mut modules = Vec::new();
    for (path, source) in sources {
        let dir = module_dir(path);
        for module in cfg_test_modules(&code_view(source)) {
            if module.body.is_none() {
                modules.push(dir.join(module.name));
            }
        }
    }
    modules
}

/// The directory that holds a file's child modules.
fn module_dir(path: &Path) -> PathBuf {
    let parent = path.parent().unwrap_or(Path::new("")).to_path_buf();
    match path.file_stem().and_then(|stem| stem.to_str()) {
        Some("mod" | "lib" | "main") | None => parent,
        Some(stem) => parent.join(stem),
    }
}

#[test]
fn redaction_canary_keeps_play_session_ids_out_of_native_traces() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut files = Vec::new();
    collect_rust_files(&root, &mut files);
    let sources: Vec<(PathBuf, String)> = files
        .into_iter()
        .map(|path| {
            let text = fs::read_to_string(&path).expect("source file should be readable");
            let relative = path.strip_prefix(&root).expect("under src").to_path_buf();
            (relative, text)
        })
        .collect();

    let result = scan(&sources);
    assert!(
        result.hits.is_empty(),
        "native traces could name a session or an id: {:#?}",
        result.hits
    );
    // The rule reaches production modules without a list and skips test files.
    for production in [
        "lib.rs",
        "commands.rs",
        "realtime.rs",
        "surface.rs",
        "surface/linux.rs",
        "player/mod.rs",
        "player/controller.rs",
        "player/events.rs",
        "media_controls.rs",
        "media_controls/mpris.rs",
        "player/hls/session.rs",
        "player/hls/loopback.rs",
        "discovery.rs",
    ] {
        assert!(
            result.scanned.contains(Path::new(production)),
            "{production} was not scanned"
        );
    }
    for test_only in [
        "trace_canary.rs",
        "trace_canary/traces.rs",
        "command_allowlist.rs",
        "player/redaction_canary.rs",
        "player/media_auth_wire/tracks.rs",
        "player/tracks/tests.rs",
        "realtime/tests/socket.rs",
        "media_controls/tests.rs",
        "media_controls/mpris/tests.rs",
        "player/hls/session_tests.rs",
        "player/media_auth_wire/hls_session.rs",
        "player/test_http.rs",
        "discovery/tests.rs",
    ] {
        assert!(
            sources.iter().any(|(path, _)| path == Path::new(test_only)),
            "{test_only} no longer exists; update this list"
        );
        assert!(
            !result.scanned.contains(Path::new(test_only)),
            "{test_only} should be test-only"
        );
    }
}
